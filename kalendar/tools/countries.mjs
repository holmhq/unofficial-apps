// Builds web/src/countries.js: each IANA time zone's country, from the tz
// database's zone.tab and iso3166.tab (public domain), so Insights can say
// where visitors are from the zone their browser reports.
//
//   node kalendar/tools/countries.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = process.argv[2] || '/usr/share/zoneinfo'
const rows = (file) => readFileSync(join(dir, file), 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split('\t'))
const SHORT = { 'Britain (UK)': 'United Kingdom', 'Korea (South)': 'South Korea', 'Korea (North)': 'North Korea' }
const names = Object.fromEntries(rows('iso3166.tab').map(([code, name]) => [code, SHORT[name] || name.replace(/ \(.*\)$/, '')]))
const zones = {}
for (const [code, , zone] of rows('zone.tab')) zones[zone] = code
// Old names browsers still report.
const LINKS = { 'Asia/Calcutta': 'IN', 'Asia/Saigon': 'VN', 'Asia/Katmandu': 'NP', 'Asia/Rangoon': 'MM', 'Europe/Kiev': 'UA', 'America/Buenos_Aires': 'AR', 'Atlantic/Faeroe': 'FO', 'Pacific/Truk': 'FM', 'Pacific/Ponape': 'FM', 'Pacific/Enderbury': 'KI' }
Object.assign(zones, LINKS)
const out = `// Generated by tools/countries.mjs from the tz database (public domain).
// Each time zone's country, for Insights. Don't edit by hand.
export const COUNTRY = ${JSON.stringify(names)}
export const ZONE = ${JSON.stringify(zones)}
`
const target = join(dirname(fileURLToPath(import.meta.url)), '../web/src/countries.js')
writeFileSync(target, out)
console.log(`${Object.keys(zones).length} zones, ${Object.keys(names).length} countries → ${target} (${out.length} bytes)`)
