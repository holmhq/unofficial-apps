// Writes web/src/icons.js from a local Lucide package: node tools/icons.mjs <lucide-dir>
// Lucide is ISC licensed; its licence sits in web/vendor/lucide/LICENSE. Shelf's own mark is
// read from holm.symbol.svg, so the app, its icons and the store show the same drawing.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const dir = process.argv[2]
const NAMES = ['book-open', 'bookmark', 'bookmark-plus', 'archive', 'highlighter', 'star', 'headphones', 'a-large-small', 'sparkles', 'list',
  'notebook-pen', 'link', 'clipboard-paste', 'file-up', 'tag', 'search', 'plus', 'x', 'check', 'chevron-left', 'chevron-right', 'chevron-down',
  'chevron-up', 'arrow-left', 'info', 'share', 'copy', 'ellipsis', 'pencil', 'rotate-ccw', 'sun', 'moon', 'sun-moon', 'log-out', 'user',
  'chart-column', 'clock', 'external-link', 'loader-circle', 'panel-left', 'trash', 'play', 'pause', 'square', 'skip-forward', 'skip-back',
  'quote', 'undo-2', 'inbox', 'circle-check', 'triangle-alert', 'wifi-off', 'refresh-cw', 'bot', 'globe', 'keyboard', 'arrow-up-right', 'minus',
  'timer', 'text-quote', 'download', 'file-text', 'image', 'plug', 'mouse-pointer-click', 'smartphone', 'library-big', 'message-square']
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const lines = []
for (const name of NAMES) {
  const file = `${dir}/dist/esm/icons/${name}.mjs`
  if (!existsSync(file)) { console.error('missing', name); continue }
  const src = readFileSync(file, 'utf8')
  const body = src.slice(src.indexOf('= [') + 2, src.lastIndexOf('];') + 1)
  const nodes = JSON.parse(body.replace(/(\w+):/g, '"$1":').replace(/,\s*\]/g, ']'))
  const svg = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('')
  lines.push(`  ${camel(name)}: '${svg}',`)
}
const symbol = readFileSync(new URL('../holm.symbol.svg', import.meta.url), 'utf8')
const mark = symbol.match(/ d="([^"]+)"/)[1]
const HOLM = 'M4.667 0h22.666A4.667 4.667 0 0 1 32 4.667v22.666A4.667 4.667 0 0 1 27.333 32H4.667A4.667 4.667 0 0 1 0 27.333V4.667A4.667 4.667 0 0 1 4.667 0ZM6.75 16h18.5c.414 0 .75.336.75.75v10.5c0 .414-.336.75-.75.75h-4.5a.75.75 0 0 1-.75-.75v-4.5a.75.75 0 0 0-.75-.75h-6.5a.75.75 0 0 0-.75.75v4.5c0 .414-.336.75-.75.75h-4.5a.75.75 0 0 1-.75-.75v-10.5c0-.414.336-.75.75-.75Zm0-12h4.5c.414 0 .75.336.75.75v7.5c0 .414-.336.75-.75.75h-4.5a.75.75 0 0 1-.75-.75v-7.5c0-.414.336-.75.75-.75Zm14 0h4.5c.414 0 .75.336.75.75v7.5c0 .414-.336.75-.75.75h-4.5a.75.75 0 0 1-.75-.75v-7.5c0-.414.336-.75.75-.75Z'

const out = `// Icons from Lucide (ISC licence, in /vendor/lucide/LICENSE), drawn on a 24 × 24 grid, plus
// Shelf's own mark and the Holm mark. Generated by tools/icons.mjs; don't edit by hand.

const NS = 'http://www.w3.org/2000/svg'
const PATHS = {
${lines.join('\n')}
}

export function ic(name, size = 20, stroke = 1.9) {
  const el = document.createElementNS(NS, 'svg')
  el.setAttribute('class', 'i')
  el.setAttribute('width', size)
  el.setAttribute('height', size)
  el.setAttribute('viewBox', '0 0 24 24')
  el.setAttribute('fill', 'none')
  el.setAttribute('stroke', 'currentColor')
  el.setAttribute('stroke-width', stroke)
  el.setAttribute('stroke-linecap', 'round')
  el.setAttribute('stroke-linejoin', 'round')
  el.setAttribute('aria-hidden', 'true')
  el.innerHTML = PATHS[name] || PATHS.bookOpen
  return el
}

// A filled star, for favourites.
export function starFill(size = 16) {
  const el = ic('star', size, 0)
  el.setAttribute('fill', 'currentColor')
  return el
}

// Shelf's mark: two books standing and one leaning, on a shelf (holm.symbol.svg).
export const MARK = '${mark}'
export function mark(size = 24) {
  const el = document.createElementNS(NS, 'svg')
  el.setAttribute('class', 'i mark')
  el.setAttribute('width', size)
  el.setAttribute('height', size)
  el.setAttribute('viewBox', '0 0 24 24')
  el.setAttribute('aria-hidden', 'true')
  el.innerHTML = '<path fill="currentColor" d="' + MARK + '"/>'
  return el
}

// The Holm mark, for the footer.
export const HOLM = '${HOLM}'
export function holmMark(size = 12) {
  const el = document.createElementNS(NS, 'svg')
  el.setAttribute('width', size)
  el.setAttribute('height', size)
  el.setAttribute('viewBox', '0 0 32 32')
  el.setAttribute('aria-hidden', 'true')
  el.innerHTML = '<path fill="currentColor" fill-rule="evenodd" d="' + HOLM + '"/>'
  return el
}
`
writeFileSync(new URL('../web/src/icons.js', import.meta.url), out)
console.log(`icons.js: ${lines.length} icons`)
